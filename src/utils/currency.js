// Работаем ТОЛЬКО с целыми числами (копейки/центы)

/**
 * Конвертирует сумму из стандартного формата валюты (например, рубли) в копейки/центы.
 * Использует округление до ближайшего целого для защиты от погрешностей чисел с плавающей запятой в JavaScript.
 * 
 * @param {number} amount - Сумма в стандартном формате (например, 100.55).
 * @returns {number} Сумма, переведенная в целые копейки (например, 10055).
 * @throws {Error} Ошибка, если переданное значение не является валидным числом.
 */
const toCents = (amount) => {
  if (typeof amount !== 'number' || isNaN(amount)) {
    throw new Error('Amount must be a number');
  }
  return Math.round(amount * 100);
};

/**
 * Конвертирует сумму из копеек/центов обратно в стандартный формат валюты.
 * Гарантирует возвращение числа с двумя знаками после запятой.
 * 
 * @param {number} cents - Сумма в целых копейках (например, 10055).
 * @returns {number} Сумма в стандартном формате валюты (например, 100.55).
 */
const toCurrency = (cents) => {
  return Number((cents / 100).toFixed(2));
};

/**
 * Модуль утилит для точных финансовых расчетов и конвертации валют.
 */
module.exports = { toCents, toCurrency };
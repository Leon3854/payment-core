
/**
 * @file merchants.js
 * @description Локальный ин-мемори регистр конфигураций мерчантов (Заглушка СУБД для тестового контура).
 * Хранит процентные ставки комиссий для расчета чистых сумм зачислений в копейках.
 */

/**
 * @typedef {object} MerchantConfig
 * @property {number} feePercent - Процентная ставка комиссии мерчанта в виде десятичной дроби (например, 0.03 для 3%)
 * @property {string} name - Коммерческое наименование торговой точки (мерчанта)
 */

/**
 * Имитация таблицы мерчантов в базе данных
 * @type {Record<string, MerchantConfig>}
 */
// В реальном проекте это было бы в БД
const merchants = {
  'merchant_001': { feePercent: 0.03, name: 'Shop A' },
  'merchant_002': { feePercent: 0.05, name: 'Shop B' }
};

/**
 * Получить конфигурационные настройки мерчанта по его идентификатору.
 * @param {string} merchantId - Уникальный идентификатор мерчанта из тела POST-запроса инвойса
 * @returns {MerchantConfig} Объект конфигурации с процентом комиссии и именем
 * @throws {Error} Ошибка "Merchant not found", если идентификатор отсутствует в регистре СУБД
 */
const getMerchantConfig = (merchantId) => {
  const config = merchants[merchantId];
  if (!config) throw new Error('Merchant not found');
  return config;
};

/**
 * Экспорт функции извлечения конфигураций мерчантов
 * @exports { getMerchantConfig }
 */
module.exports = { getMerchantConfig };




